# Bitwise AND
a=8
b=10

print("Bitwise AND Opeartion result is",a & b)

# Bitwise OR
print("Bitwise OR Operation result is ",a | b)

# Bitwise XOR
print("Bitwise XOR Operation result is ",a ^ b)

#Bitwise Left Shift
print("Bitwise Left Shift Operation result is", a<<1)

#Bitwise Right Shift
print("Bitwise Right Shift Operation result is", a>>1)